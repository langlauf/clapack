int contains_unused(char *string)
{

int i,k;
char *ptr;
int found, f_pos, l_pos;

  /* Search to see if string contains an unused variable. */

  for (i = 0; i < unused_index; ++i) {

    /* printf("searching not_used_table >>%s<<  \n",not_used_table[i].name);  */

    k = 0;
    while (ptr = strstr(&string[k], not_used_table[i].name)) {
      /* now need to check that haven't got a sub-string of another variable */
      f_pos = ptr - string;
      l_pos = f_pos + strlen(not_used_table[i].name) - 1;
      /* check that have non-alphanumeric delimiters */
      if(f_pos) 
        found = !isalnum(string[f_pos-1]) && ! isalnum(string[l_pos + 1]);
      else
        found = isalnum(string[l_pos + 1]);
       
      if(found) return 1;

      k = l_pos + 1;    

    }




  }

  return 0;

}

