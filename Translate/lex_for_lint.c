int lookup_not_used(char *name)
{

int i,k;
char search_name[100];

  /* search to see if have an unused variable */

  k = 0;
  for (i = 0; i < strlen(name); ++i)
    if(!isspace(name[i])) {
      search_name[k] = name[i];
      ++k;
    }
  search_name[k] = '\0';
   
  for (i = 0; i < unused_index; ++i) {
    /* printf("searching not_used_table >>%s<<  \n",not_used_table[i].name);  */
     if (!strcmp(not_used_table[i].name,search_name)) return 1;
  }

  return 0;

}

